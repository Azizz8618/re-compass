* Финальная правка ядра МАРС (накладывается на бинарник зоны 0657).
* Исходник re-mars-fixed.asm НЕ меняется: любая вставка сдвигает метки
* и ломает загрузку модуля (см. REPORT.md). Метки и адреса остаются
* прежними; используется свободный хвост зоны 0657 (03720..03722).
*
* Было (03440, вторая половина слова):
*   ЗП DBLEN ; УИ M5        ; M5 := DBLEN, аккумулятор = DBLEN
* Стало:
*   ЗП DBLEN ; ПБ 03720     ; уход в трамплин
*
* Трамплин (свободные нулевые слова 03720, 03721, 03722):
* 03720: УИ M5              ; сохранить индекс зоны (как в оригинале)
* 03720: СЧ E11             ; 1024 в аккумуляторе
* 03721: ВЧ DBLEN           ; 1024 - DBLEN, аддитивный режим
* 03721: ПЕ OVERFL          ; если отрицательно (DBLEN > 1024) -> ошибка 06
* 03722: ПБ 03441           ; вернуться к исходным СЧ DBDESC / И E18П1
*
* Замечание о исходном патче re-mars-limit-1024.patch:
*   НТЖ - побитовое XOR, ПО после него переходит при равенстве,
*   поэтому «НТЖ E11; ПО OVERFL» ловит 1024, но пропускает 1025.
*   Для проверки «больше» используется вычитание и ПЕ в аддитивном режиме.
